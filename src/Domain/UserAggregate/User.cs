using CqrsApiExample.Domain.Common.DomainErrors;
using CqrsApiExample.Domain.Common.Models;
using CqrsApiExample.Domain.Common.Results;
using CqrsApiExample.Domain.UserAggregate.Events;

namespace CqrsApiExample.Domain.UserAggregate;

/// <summary>
///     A registered user. This is the aggregate root of the users area: repositories
///     load and save it as a whole, and it is the only object that raises events
///     about users.
/// </summary>
/// <remarks>
///     The class knows nothing about persistence: the mapping lives in
///     <c>Infrastructure/Persistence/Configurations/UserConfiguration.cs</c>, which reuses the
///     max-length constants below, and the audit fields (<c>CreatedAt</c>/<c>ModifiedAt</c>)
///     are filled by the infrastructure when the user is saved.
/// </remarks>
public sealed class User : AggregateRoot
{
    // Shared with the EF mapping (column sizes) and the FluentValidation validators,
    // so the database, the input checks and the invariants below never disagree.
    public const int NameMaxLength = 100;
    public const int SurnameMaxLength = 100;
    public const int EmailMaxLength = 256;

    // Private so that Create is the only way to build a valid user from outside.
    // EF Core also uses it to materialize users read from the database; the Id is
    // generated by Entity (Guid v7) and overwritten by EF with the stored value.
    private User(string name, string surname, string email)
    {
        Name = name;
        Surname = surname;
        Email = email;
    }

    // Private setters: state only changes through the aggregate's own methods.
    public string Name { get; private set; }
    public string Surname { get; private set; }
    public string Email { get; private set; }

    /// <summary>
    ///     Creates a user, enforcing the domain invariants, and raises
    ///     <see cref="UserCreatedDomainEvent"/>.
    /// </summary>
    /// <returns>
    ///     The new user, or every invariant that failed (not just the first),
    ///     as <see cref="Error"/> values instead of exceptions.
    /// </returns>
    public static Result<User> Create(string name, string surname, string email)
    {
        // The validators in the Application already check the input format; these checks
        // repeat it on purpose, so the domain stays valid whoever calls it. The error codes
        // are the same, so the API answers the same way whichever layer catches the problem.
        List<Error> errors = [];

        if (string.IsNullOrWhiteSpace(name) || name.Trim().Length > NameMaxLength)
        {
            errors.Add(Errors.Users.InvalidName);
        }

        if (string.IsNullOrWhiteSpace(surname) || surname.Trim().Length > SurnameMaxLength)
        {
            errors.Add(Errors.Users.InvalidSurname);
        }

        if (string.IsNullOrWhiteSpace(email) || email.Trim().Length > EmailMaxLength)
        {
            errors.Add(Errors.Users.InvalidEmail);
        }

        if (errors.Count > 0)
        {
            return errors;
        }

        string trimmedName = name.Trim();
        string trimmedSurname = surname.Trim();

        // Emails are stored lowercase, so the unique index treats "A@x.com" and "a@x.com"
        // as the same address. Email uniqueness itself is not checked here: it needs the
        // database (ExistsByEmailAsync plus the unique index).
        string normalizedEmail = email.Trim().ToLowerInvariant();

        User user = new(trimmedName, trimmedSurname, normalizedEmail);

        // The event is only recorded in the aggregate: nothing is sent and nobody is notified yet.
        // When the command handler commits, the unit of work writes it to the outbox in the same
        // transaction as the user, so it exists if and only if the user was saved. A background
        // service then delivers it to the IDomainEventHandler<UserCreatedDomainEvent> handlers
        // (for example, the welcome email), at least once.
        // The event carries the data its handlers need, so they don't have to load the user again.
        // It is stored by its full type name: renaming, moving or reshaping it breaks pending messages.
        UserCreatedDomainEvent domainEvent = new(user.Id, user.Name, user.Surname, user.Email);

        user.RaiseDomainEvent(domainEvent);

        return user;
    }
}
